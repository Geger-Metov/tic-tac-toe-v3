class GameNotFoundError(Exception):
    """Игра с таким id не найдена — веб-слой превращает это в 404."""
    pass


class NotParticipantError(Exception):
    """Пользователь не X и не O в этой игре — веб-слой превращает это в 403."""
    pass


class InvalidTurnError(Exception):
    """Сейчас не очередь этого игрока (или игра уже окончена/ещё ждёт второго
    игрока) — веб-слой превращает это в 409."""
    pass


class InvalidMoveError(Exception):
    """Ход не соответствует правилам (не одна клетка, чужой символ и т.п.) —
    веб-слой превращает это в 400."""
    pass


class GameNotJoinableError(Exception):
    """Нельзя присоединиться: игра уже заполнена, это игра с компьютером, или
    попытка присоединиться к собственной игре — веб-слой превращает это в 409."""
    pass
